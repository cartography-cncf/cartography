def test_every_generated_module_renders_documented_content():
    """Covers the exact module list the Sphinx build renders, which is not run in CI."""
    # Arrange
    model = inspect_data_model()
    modules = generated_schema_modules(model)

    # Act
    pages = {module: render_module_schema(model, module) for module in modules}

    # Assert
    assert set(modules).isdisjoint(MANUAL_SCHEMA_MODULES)
    assert len(modules) > 40
    for module, page in pages.items():
        node_headings = [
            line.removeprefix("### ")
            for line in page.splitlines()
            if line.startswith("### ")
        ]
        assert page.startswith(GENERATED_NOTICE), module
        assert node_headings, module
        assert node_headings == sorted(node_headings, key=str.casefold), module
        assert "No description provided." not in page, module


