def test_ontology_and_cross_module_relationships_are_duplicated_in_module_docs():
    # Arrange
    node = Node(
        label="LastpassUser",
        descriptions=(),
        extra_labels=("UserAccount",),
        conditional_labels=(),
        properties=(),
        modules=("lastpass",),
        schemas=(),
        ontology_labels=("UserAccount",),
    )
    # The canonical User node is what lets a provider page document HAS_ACCOUNT even
    # though the provider never declares that edge.
    canonical_user = Node(
        label="User",
        descriptions=(),
        extra_labels=(),
        conditional_labels=(),
        properties=(),
        modules=("ontology",),
        schemas=(),
    )
    relationships = (
        Relationship(
            source_label="User",
            label="HAS_ACCOUNT",
            target_label="UserAccount",
            direction=LinkDirection.OUTWARD,
            descriptions=(),
            properties=(),
            modules=("ontology",),
            origins=("node_schema",),
            schemas=(),
            analysis_jobs=(),
        ),
        Relationship(
            source_label="Human",
            label="IDENTITY_LASTPASS",
            target_label="LastpassUser",
            direction=LinkDirection.OUTWARD,
            descriptions=(),
            properties=(),
            modules=("analysis",),
            origins=("analysis",),
            schemas=(),
            analysis_jobs=(),
        ),
    )
    model = DataModel(nodes=(node, canonical_user), relationships=relationships)

    # Act
    generated = render_module_schema(model, "lastpass")

    # Assert
    # Inherited ontology edges keep the far endpoint semantic when possible, but
    # rewrite the near endpoint to the concrete node being documented.
    assert "(:User)-[:HAS_ACCOUNT]->(:LastpassUser)" in generated
    assert "(:Human)-[:IDENTITY_LASTPASS]->(:LastpassUser)" in generated


