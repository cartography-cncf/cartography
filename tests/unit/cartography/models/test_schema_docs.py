def test_mermaid_diagram_only_covers_intra_module_edges():
    # Arrange
    model = inspect_data_model(gitlab_models)

    # Act
    generated = render_module_schema(model, "gitlab")
    mermaid = generated.split("graph LR", 1)[1].split("```", 1)[0]

    # Assert
    assert "GitLabProject -- HAS_ENVIRONMENT --> GitLabEnvironment" in mermaid
    module_labels = {node.label for node in model.nodes}
    for line in mermaid.splitlines():
        if not line.strip():
            continue
        endpoints = line.split("--")[0].strip(), line.split(">")[-1].strip()
        assert all(endpoint in module_labels for endpoint in endpoints), line


def test_relationship_property_tables_hide_internal_fields():
    # Arrange
    model = inspect_data_model(gitlab_models)

    # Act
    generated = render_module_schema(model, "gitlab")

    # Assert
    blocks = [
        block.split("\n\n", 1)[0]
        for block in generated.split("  - Properties:\n\n")[1:]
    ]
    assert blocks, "gitlab documents at least one relationship property table"
    # firstseen, lastupdated and _-prefixed bookkeeping fields carry no meaning here.
    for block in blocks:
        assert "| firstseen |" not in block
        assert "| lastupdated |" not in block
        assert "| _" not in block
    assert "linked_variable_ids" not in generated


