def test_documentation_schema_links_target_generated_headings():
    model = inspect_data_model()
    schema_link_pattern = re.compile(
        r"modules/(?P<module>[^/]+)/schema\.html#(?P<anchor>[a-z0-9_-]+)",
    )
    generated_anchors_by_module: dict[str, set[str]] = {}
    invalid_links: list[str] = []

    for path in (REPOSITORY_ROOT / "docs" / "root").rglob("*.md"):
        for match in schema_link_pattern.finditer(path.read_text()):
            module = match.group("module")
            if module not in generated_anchors_by_module:
                generated = render_module_schema(model, module)
                generated_anchors_by_module[module] = {
                    heading.lower()
                    for heading in re.findall(
                        r"^### ([A-Za-z0-9_-]+)$", generated, re.MULTILINE
                    )
                }
            if match.group("anchor") not in generated_anchors_by_module[module]:
                invalid_links.append(f"{path}: {match.group(0)}")

    assert invalid_links == []


def test_relationship_docstrings_are_user_facing_descriptions():
    # Arrange
    model = inspect_data_model()
    relationship_schema_types = {
        type(schema)
        for relationship in model.relationships
        for schema in relationship.schemas
    }
    forbidden_markers = (
        "(:",
        "```",
        "one_to_many",
        "other_relationships",
        "target_node_matcher",
        "source_node_matcher",
        "matchlink:",
        "loaded as",
        "lifecycle follows",
    )

    # Act
    violations = []
    for schema_type in sorted(
        relationship_schema_types,
        key=lambda item: (item.__module__, item.__name__),
    ):
        raw_docstring = schema_type.__doc__
        if not raw_docstring or raw_docstring.lstrip().startswith(
            f"{schema_type.__name__}(",
        ):
            continue
        docstring = inspect.cleandoc(raw_docstring)
        matched_markers = tuple(
            marker
            for marker in forbidden_markers
            if marker.casefold() in docstring.casefold()
        )
        if matched_markers:
            violations.append(
                f"{schema_type.__module__}.{schema_type.__name__}: "
                f"{', '.join(matched_markers)}",
            )

    # Assert
    assert not violations, "\n".join(violations)


